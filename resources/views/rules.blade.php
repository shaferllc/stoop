        <h1 class="font-display text-3xl font-bold">House rules</h1>
        <p class="mt-2 max-w-prose text-mute">Stoop is for talking about the city with the people who live in it. Argue about places, policies and pizza as hard as you like.</p>

        <h2 class="mt-6 font-display text-xl font-bold">Not allowed</h2>
        <ul class="mt-2 max-w-prose list-disc space-y-1.5 pl-5">
            <li><b>Attacks on people for who they are,</b> including race, ethnicity, religion, gender, sexual orientation, disability, immigration status or where they’re from.</li>
            <li><b>Profiling.</b> When you post about a crime or safety issue, describe what happened, where and when. Don’t describe a person by race alone.</li>
            <li><b>Threats and harassment,</b> including piling on someone across threads.</li>
            <li><b>Campaign posts.</b> No candidate or campaign promotion. Local issues like zoning, schools and bike lanes are fine.</li>
            <li><b>Networking and spam.</b> No job pitches, lead generation or repeated self-promotion.</li>
        </ul>

        <h2 class="mt-6 font-display text-xl font-bold">What happens when someone breaks them</h2>
        <ol class="mt-2 max-w-prose list-decimal space-y-1.5 pl-5">
            <li>A warning and the post comes down.</li>
            <li>A 24-hour mute.</li>
            <li>A 7-day suspension.</li>
            <li>A permanent ban. Slurs and threats go straight here.</li>
        </ol>
        <p class="mt-3 max-w-prose text-mute">Report anything that breaks these rules from the ··· menu on a post. It disappears for you right away, and moderators review every report.</p>
